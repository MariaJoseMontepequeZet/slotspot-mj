\set ON_ERROR_STOP on

SELECT CASE
    WHEN EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'rol')
    THEN format(
        'ALTER ROLE %I WITH LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS',
        :'rol', :'clave')
    ELSE format(
        'CREATE ROLE %I WITH LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS',
        :'rol', :'clave')
END \gexec

BEGIN;

SELECT format('REVOKE TEMPORARY ON DATABASE %I FROM PUBLIC', current_database()) \gexec
SELECT format('GRANT CONNECT ON DATABASE %I TO %I', current_database(), :'rol') \gexec

REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO :"rol";

REVOKE ALL ON ALL TABLES IN SCHEMA public FROM :"rol";
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM :"rol";

GRANT SELECT ON roles TO :"rol";
GRANT SELECT, INSERT, UPDATE ON usuarios TO :"rol";
GRANT SELECT, INSERT, UPDATE ON tipos_vehiculo TO :"rol";
GRANT SELECT, UPDATE ON slots TO :"rol";
GRANT SELECT, INSERT, UPDATE ON servicios TO :"rol";
GRANT SELECT, INSERT ON pagos TO :"rol";
GRANT SELECT, INSERT ON auditoria TO :"rol";

COMMIT;
